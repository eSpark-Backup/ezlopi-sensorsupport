struct LED_CONFIG_CHANNEL {
  enum LED_MODE mode;
  enum LED_ORIENTATION orientation;
  int16_t sx;
  int16_t sy;
  int16_t ox;
  int16_t oy;
  int16_t black[3];
  bool selected;
  uint16_t start, stop;
  int segment_id;
  int number_of_leds;
  uint32_t color[3];
  uint8_t intensity;
  uint16_t speed;
  uint8_t options;
  uint8_t palette;
};

struct LED_CONFIG {
  int16_t refresh_rate;
  uint8_t channels;
  uint8_t prefix_leds;
  struct LED_CONFIG_CHANNEL* channel[MAX_SEGMENTS];
  uint16_t artnet_width;
  uint16_t artnet_universe_offset;
  uint32_t config_color[3];
  int total_leds;
};



